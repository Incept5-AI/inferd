#!/usr/bin/env python3
# summarize.py: one markdown summary of every benchmark-queue result pulled by collect.py
# (~/dev/inference/results/fleet-queue/<host>/results/<job>/). Prints markdown; used for the repo's
# results/queue-<date>/README.md and the reports. Rows: follow-ups (total tok/s per agent count), fleets
# (turns/min per cell), scenarios (TTFT medians per phase), single agent (first token / decode).
import json, pathlib, re, sys

ROOT = pathlib.Path.home() / "dev/inference/results/fleet-queue"
MACHINE = {"mini-m6": "M6 32 GB (macOS 27.0)", "mini-m6-2": "M6 32 GB (macOS 27.2)", "mini-m5-pro": "M5 Pro 64 GB",
           "mini-m5-pro-2": "M5 Pro 64 GB (2)", "mini-m4-pro": "M4 Pro 64 GB"}
CONC = re.compile(r"\s*(\d+k)\s+(\d+)\s+(\d+)\s+(\d+)\s+([\d.]+)\s+([\d.]+)\s+[\d.]+\s+[\d.]+\s+([\d.]+)\s+([\d.]+)")


def conc_rows(f):
    return [m.groups() for m in map(CONC.match, f.read_text(errors="replace").splitlines()) if m]


def engine(label):
    return "TensorFold 1.2.2" if label.startswith("tf122") else "Splash 1.5" if label.startswith("splash") else "inferd 0.2.0"


def model(label):
    return "Qwen3.5-9B 8-bit" if "q9b8" in label else "Qwen3.5-9B 4-bit" if ("q9b4" in label or "q9" in label) else "Qwen3.8-27B 4-bit"


follow, fleets, scens, singles = {}, [], [], []
for host in sorted(p.name for p in ROOT.iterdir() if p.is_dir()):
    for job in sorted((ROOT / host / "results").glob("*")):
        if job.name.startswith("00") and "m6mem" in job.name:
            continue  # engine A/B jobs: reported by the engine work, not here
        for f in sorted(job.glob("followup-*.txt")):
            lab = f.stem[len("followup-"):]
            for ctx, n, ok, err, wall, tps, tmed, tmax in conc_rows(f):
                if int(err) == 0 and ok == n:
                    follow.setdefault((host, model(lab), ctx), {}).setdefault(engine(lab), {}).setdefault(int(n), []).append(float(tps))
        for f in sorted(job.glob("single-*.txt")):
            lab = f.stem[len("single-"):].split("-r")[0]
            for ctx, n, ok, err, wall, tps, tmed, tmax in conc_rows(f):
                singles.append((host, model(lab), engine(lab), ctx, float(tmed)))
        fj = job / "fleet.jsonl"
        if fj.exists():
            for ln in fj.read_text(errors="replace").splitlines():
                try:
                    r = json.loads(ln)
                except Exception:
                    continue
                if "turns_per_min" in r and r.get("err", 0) == 0 and r.get("ok") == r.get("turns", r.get("ok")):
                    lab = r.get("label", "")
                    fleets.append((host, model(lab), engine(lab), r.get("running") or r.get("n") or r.get("agents"), r["turns_per_min"]))
        for f in sorted(job.glob("scen-*.txt")):
            lab = f.stem[len("scen-"):]
            for ln in f.read_text(errors="replace").splitlines():
                m = re.match(r"\s+(.+?)\s+n=(\d+)\s+err=(\d+)\s+TTFT med ([\d.]+)", ln)
                if m:
                    scens.append((host, model(lab), engine(lab), m.group(1).strip(), int(m.group(2)), int(m.group(3)), float(m.group(4))))


def rng(v):
    return f"{min(v):.1f}" if len(v) == 1 or max(v) - min(v) < 0.05 else f"{min(v):.1f}–{max(v):.1f}"


out = ["# Benchmark queues, 4 November 2026", "",
       "Every mini ran a job queue (one model at a time) with inferd 0.2.0 (prebuilt), TensorFold 1.2.2 and Splash 1.5",
       "where installed, on the same checkpoints and harness (`bench/studio/conc.py`, the 8k agent-fleet harness,",
       "`bench/agents_scenarios.py`). Only complete cells (every request served, 0 errors) are listed. Raw files in the",
       "per-machine folders. Generated by bench-queue/summarize.py.", "",
       "## Follow-up turns: total tok/s by number of agents", ""]
for (host, mdl, ctx), engines in sorted(follow.items(), key=lambda x: (x[0][1], x[0][0], int(x[0][2][:-1]))):
    ns = sorted({n for e in engines.values() for n in e})
    out.append(f"**{MACHINE.get(host, host)}, {mdl}, {ctx} contexts**")
    out.append("")
    out.append("| engine | " + " | ".join(f"{n} agents" for n in ns) + " |")
    out.append("|---|" + "---:|" * len(ns))
    for eng, cells in sorted(engines.items()):
        out.append(f"| {eng} | " + " | ".join(rng(cells[n]) if n in cells else "–" for n in ns) + " |")
    out.append("")
if fleets:
    out += ["## Agent fleets (8k contexts): completed turns per minute", "", "| machine | model | engine | agents | turns/min |", "|---|---|---|---:|---:|"]
    out += [f"| {MACHINE.get(h, h)} | {m} | {e} | {n} | {t:.1f} |" for h, m, e, n, t in fleets]
    out.append("")
if scens:
    out += ["## Agent scenarios: first-token medians", "", "| machine | model | engine | phase | n | err | TTFT median (s) |", "|---|---|---|---|---:|---:|---:|"]
    out += [f"| {MACHINE.get(h, h)} | {m} | {e} | {p} | {n} | {er} | {t:.2f} |" for h, m, e, p, n, er, t in scens]
    out.append("")
print("\n".join(out))
